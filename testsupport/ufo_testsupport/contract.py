class _Definitions(GenerateJsonSchema):
    """Every model under one `$defs`, the root included, so one walk renders them all."""

    def generate(self, schema: Any, mode: JsonSchemaMode = MODE) -> dict[str, Any]:
        rendered = super().generate(schema, mode=mode)
        title = rendered.pop("title")
        defs = rendered.pop("$defs", {})
        defs[title] = rendered
        return {"$defs": defs}


def _reference(schema: dict[str, Any]) -> str | None:
    ref = schema.get("$ref")
    return None if ref is None else ref.rsplit("/", 1)[-1]


def _union_name(members: list[dict[str, Any]], aliases: dict[frozenset[str], str]) -> str | None:
    refs = [_reference(member) for member in members]
    if any(ref is None for ref in refs):
        return None
    return aliases.get(frozenset(ref for ref in refs if ref is not None))


def _render_type(schema: dict[str, Any], aliases: dict[frozenset[str], str]) -> str:
    named = _reference(schema)
    if named is not None:
        return named
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(value) for value in schema["enum"])
    members = schema.get("anyOf") or schema.get("oneOf")
    if members is not None:
        return _union_name(members, aliases) or " | ".join(
            _render_type(member, aliases) for member in members
        )
    kind = schema.get("type")
    if kind in SCALARS:
        return SCALARS[kind]
    if kind == "null":
        return "null"
    if kind == "array":
        item = _render_type(schema["items"], aliases)
        return (f"({item})" if " | " in item else item) + "[]"
    if kind == "object":
        extra = schema.get("additionalProperties")
        value = _render_type(extra, aliases) if isinstance(extra, dict) else "unknown"
        return f"Record<string, {value}>"
    return "unknown"


def _render_model(name: str, schema: dict[str, Any], aliases: dict[frozenset[str], str]) -> str:
    """A field with a default is optional, except a discriminator: its one value is always
    serialized, and a union narrows on it only when it is required."""
    required = set(schema.get("required", ()))
    lines = [f"export type {name} = {{"]
    for field, held in schema.get("properties", {}).items():
        mark = "" if field in required or "const" in held else "?"
        lines.append(f"  {field}{mark}: {_render_type(held, aliases)};")
    lines.append("};")
    return "\n".join(lines)


def rendered_contract() -> str:
    """The TypeScript module: one type per model `TurnRecord` reaches, and one alias per union
    the record names."""
    defs = TypeAdapter(ROOT).json_schema(schema_generator=_Definitions, mode=MODE)["$defs"]
    defs.update(
        TypeAdapter(ExportView).json_schema(schema_generator=_Definitions, mode=MODE)["$defs"]
    )
    aliases: dict[frozenset[str], str] = {}
    for name, union in ALIASES.items():
        members = TypeAdapter(union).json_schema(mode=MODE)["oneOf"]
        aliases[frozenset(ref for ref in (_reference(m) for m in members) if ref)] = name
    parts = [HEADER]
    parts.extend(_render_model(name, defs[name], aliases) for name in sorted(defs))
    parts.extend(
        f"export type {name} = {' | '.join(sorted(members))};"
        for members, name in sorted(aliases.items(), key=lambda held: held[1])
    )
    return "\n\n".join(parts) + "\n"


def _rust_type(schema: dict[str, Any], aliases: dict[frozenset[str], str]) -> str:
    """The Rust type a schema renders to. A string literal set is a `String` here — the tagged
    enums the unions need are the one place Rust reads a literal — and a nullable type an
    `Option`."""
    named = _reference(schema)
    if named is not None:
        return named
    if "const" in schema or "enum" in schema:
        return "String"
    members = schema.get("anyOf") or schema.get("oneOf")
    if members is not None:
        alias = _union_name(members, aliases)
        if alias is not None:
            return alias
        held = [member for member in members if member.get("type") != "null"]
        inner = _rust_type(held[0], aliases) if len(held) == 1 else "serde_json::Value"
        return f"Option<{inner}>" if len(held) < len(members) else inner
    kind = schema.get("type")
    if kind in RUST_SCALARS:
        return RUST_SCALARS[kind]
    if kind == "array":
        return f"Vec<{_rust_type(schema['items'], aliases)}>"
    return "serde_json::Value"


def _rust_field(name: str, schema: dict[str, Any], required: bool, aliases: Any) -> list[str]:
    rendered = _rust_type(schema, aliases)
    optional = not required and not rendered.startswith("Option<")
    if optional:
        rendered = f"Option<{rendered}>"
    lines: list[str] = []
    if rendered.startswith("Option<"):
        lines.append('    #[serde(default, skip_serializing_if = "Option::is_none")]')
    ident = f"r#{name}" if name in RUST_KEYWORDS else name
    lines.append(f"    pub {ident}: {rendered},")
    return lines


def _rust_struct(name: str, schema: dict[str, Any], aliases: dict[frozenset[str], str]) -> str:
    required = set(schema.get("required", ()))
    lines = ["#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]", f"pub struct {name} {{"]
    for field, held in schema.get("properties", {}).items():
        lines.extend(_rust_field(field, held, field in required, aliases))
    lines.append("}")
    return "\n".join(lines)


def _rust_enum(
    name: str, members: list[str], defs: dict[str, Any], aliases: dict[frozenset[str], str]
) -> str:
    """A discriminated union as a tagged enum: each member's fields ride the variant, and the
    discriminator is the tag serde reads, so the member structs are not emitted on their own.
    rustfmt folds a short variant onto one line, so the enum is skipped and stays as rendered; the
    variants take the contract's shape, so their size spread is not clippy's to judge."""
    lines = [
        "#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]",
        '#[serde(tag = "kind")]',
        "#[rustfmt::skip]",
        "#[allow(clippy::large_enum_variant)]",
        f"pub enum {name} {{",
    ]
    for member in members:
        schema = defs[member]
        tag = schema["properties"]["kind"]["const"]
        variant = "".join(part.capitalize() for part in tag.split("_"))
        lines.append(f'    #[serde(rename = "{tag}")]')
        fields = [(field, held) for field, held in schema["properties"].items() if field != "kind"]
        if not fields:
            lines.append(f"    {variant},")
            continue
        lines.append(f"    {variant} {{")
        required = set(schema.get("required", ()))
        for field, held in fields:
            lines.extend(
                "    " + line.replace("    pub ", "    ", 1)
                for line in _rust_field(field, held, field in required, aliases)
            )
        lines.append("    },")
    lines.append("}")
    return "\n".join(lines)


def rendered_rust() -> str:
    """The Rust module the terminal client folds into: one struct per model the record reaches,
    one tagged enum per union it names."""
    defs = TypeAdapter(ROOT).json_schema(schema_generator=_Definitions, mode=MODE)["$defs"]
    aliases: dict[frozenset[str], str] = {}
    unions: dict[str, list[str]] = {}
    for name, union in ALIASES.items():
        members = TypeAdapter(union).json_schema(mode=MODE)["oneOf"]
        refs = [ref for ref in (_reference(m) for m in members) if ref]
        aliases[frozenset(refs)] = name
        unions[name] = refs
    variants = {member for members in unions.values() for member in members}
    parts = [RUST_HEADER, "use serde::{Deserialize, Serialize};"]
    parts.extend(
        _rust_struct(name, defs[name], aliases) for name in sorted(defs) if name not in variants
    )
    parts.extend(_rust_enum(name, unions[name], defs, aliases) for name in sorted(unions))
    return "\n\n".join(parts) + "\n"


