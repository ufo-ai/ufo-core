def conformance_cases() -> list[tuple[str, tuple[LiveFrame, ...]]]:
    """Frame sequences every fold must fold alike: the words, steps, drains, replies, resumes, runs
    and ends a turn can put on its stream, in the orders that decide a record's shape."""
    page = SourceRef(kind="web", title="Docs", url="https://docs.example/a")
    plan = SourceRef(kind="workspace", title="Plan", ref="page/1", provider="notion")
    done = Terminal(
        frame=TerminalFrame(
            status="done",
            text="It shipped Tuesday.",
            tokens=12,
            cost_micro_usd=110,
            model="claude-opus-4-8",
        )
    )
    run = SubagentActivity(
        turn_id=RUN_ID,
        parent_turn_id=TURN_ID,
        conversation_id=RUN_CONVERSATION_ID,
        profile="deep_research",
        name="Calendar check",
    )
    child = SubagentActivity(
        turn_id=CHILD_RUN_ID,
        parent_turn_id=RUN_ID,
        conversation_id=CHILD_CONVERSATION_ID,
        profile="general_purpose",
    )
    return [
        (
            "words between two tool steps, then the answer",
            (
                TextDelta(text="Reading the changelog first."),
                Activity(text="Reading the changelog.", call_id="c1"),
                TextDelta(text="Checking the tags now."),
                Activity(text="Checking the release tags.", call_id="c2"),
                TextDelta(text="It shipped "),
                TextDelta(text="Tuesday."),
                done,
            ),
        ),
        (
            "sources before any label open an unlabelled step, and words close it",
            (
                Sources(items=(page,)),
                Sources(items=(page, plan)),
                TextDelta(text="Here."),
                Activity(text="Listing."),
                Sources(items=(plan,)),
                done,
            ),
        ),
        (
            "a drain cuts the round, a replayed reply states itself once, a comment is kept",
            (
                Reply(id=REPLY_ID, message_ref=ARRIVAL_ID, text="Filed it."),
                Reply(id=REPLY_ID, message_ref=ARRIVAL_ID, text="Filed it."),
                Absorbed(arrivals=(ARRIVAL_ID,)),
                Absorbed(arrivals=(ARRIVAL_ID,)),
                TextDelta(text="2"),
                CostTick(cost_micro_usd=110, tokens=12),
                Reply(id=COMMENT_ID, text="A comment landed on Slack.", is_comment=True),
                Terminal(frame=TerminalFrame(status="done", text="2", model="claude-opus-4-8")),
            ),
        ),
        (
            "a resume between words, then a park",
            (
                TextDelta(text="Half"),
                Resumed(attempt=ATTEMPT),
                TextDelta(text="way"),
                Parked(message="Spend cap reached; the turn resumes when the cap is raised."),
            ),
        ),
        (
            "a run nests its child under it and both end",
            (
                run,
                run.model_copy(update={"activity": "Reading the calendar."}),
                child,
                child.model_copy(update={"activity": "Looking up info"}),
                child.model_copy(update={"status": "done"}),
                run.model_copy(update={"status": "done"}),
                done,
            ),
        ),
    ]


def rendered_fold() -> str:
    """Each case as the stream would deliver it — the web surface's own SSE rows — beside the record
    the reference fold reaches, with no null field, so a fold in any language replays the rows and
    compares its record after dropping its own nulls."""
    cases = []
    for name, frames in conformance_cases():
        record = TurnRecord(id=TURN_ID, steps=(), runs=(), meter=None, end=None)
        for frame in frames:
            record = fold(record, frame, ENDED_AT)
        cases.append(
            {
                "name": name,
                "frames": [_row(_sse("", frame)) for frame in frames],
                "record": record.model_dump(mode="json", exclude_none=True),
            }
        )
    return json.dumps(cases, indent=2, ensure_ascii=False) + "\n"


def write_contract() -> None:
    CONTRACT_PATH.write_text(rendered_contract())
    RUST_CONTRACT_PATH.write_text(rendered_rust())
    RECORD_FIXTURE_PATH.parent.mkdir(parents=True, exist_ok=True)
    RECORD_FIXTURE_PATH.write_text(rendered_record())
    FOLD_FIXTURE_PATH.write_text(rendered_fold())


if __name__ == "__main__":
    write_contract()
    for written in (CONTRACT_PATH, RUST_CONTRACT_PATH, RECORD_FIXTURE_PATH, FOLD_FIXTURE_PATH):
        print(f"wrote {written}")
